def subtract_two_number(first_number, second_number):
    minus_of_numbers = first_number - second_number
    return minus_of_numbers


def divide_two_number(first_number, second_number):
    division_of_numbers = first_number / second_number
    return division_of_numbers



def multiply_two_number(first_number, second_number):
    product_of_numbers = first_number * second_number
    return product_of_numbers










result = subtract_two_number(25, 40)
print(result)

result = divide_two_number(25, 40)
print(result)

result = multiply_two_number(25, 40)
print(result)




